import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';

const root = resolve(import.meta.dirname, '..');
const temporary = await mkdtemp(resolve(tmpdir(), 'proview-contract-'));
const check = process.argv.includes('--check');
try {
  const output = resolve(temporary, 'openapi.json');
  const child = spawn(process.execPath, ['scripts/export-openapi.cjs', output], {
    cwd: resolve(root, 'apps/api'),
    stdio: 'inherit',
    env: {
      ...process.env,
      APP_ENV: 'test',
      DATABASE_URL: 'postgresql://unused:unused@127.0.0.1:1/unused?schema=public',
      JWT_ACCESS_SECRET: 'contract-export-only-key-no-server-no-database-123456789',
      FRONTEND_URL: 'http://localhost:3000',
      STORAGE_DRIVER: 'local',
    },
  });
  const [code] = await once(child, 'exit');
  if (code !== 0) throw new Error('Build the API before exporting contracts.');
  const document = JSON.parse(await readFile(output, 'utf8'));
  const format = await prettier.resolveConfig(resolve(root, 'package.json'));
  const spec = await prettier.format(JSON.stringify(document), { ...format, parser: 'json' });
  const types = await prettier.format(
    `// Generated by pnpm api:generate. Do not edit.\n${astToString(await openapiTS(document))}`,
    { ...format, parser: 'typescript' },
  );
  for (const [path, contents] of [
    ['docs/api.openapi.json', spec],
    ['apps/web/lib/api/generated.ts', types],
  ]) {
    const target = resolve(root, path);
    if (check) {
      if ((await readFile(target, 'utf8')) !== contents)
        throw new Error(`${path} drifted. Run pnpm api:generate and commit both outputs.`);
    } else await writeFile(target, contents);
  }
  let covered = 0;
  let total = 0;
  for (const path of Object.values(document.paths)) {
    for (const method of ['get', 'post', 'put', 'patch', 'delete']) {
      const operation = path[method];
      if (!operation) continue;
      total++;
      if (
        Object.entries(operation.responses).some(
          ([status, response]) =>
            status.startsWith('2') &&
            Object.values(response.content ?? {}).some((media) => media.schema),
        )
      )
        covered++;
    }
  }
  console.log(
    `PASS API ${check ? 'drift check' : 'generation'}; success response schemas ${covered}/${total}.`,
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
